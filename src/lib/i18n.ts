export type Locale = keyof typeof translations;

type DeepRecord<T> = { [K in keyof T]: T[K] extends Record<string, unknown> ? DeepRecord<T[K]> : string };

const STORAGE_KEY = "compass_lang";

export function getLocale(): Locale {
  if (typeof window === "undefined") return "en";
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === "hi" || stored === "en") return stored;
  return "en";
}

export function setLocale(locale: Locale): void {
  if (typeof window !== "undefined") {
    localStorage.setItem(STORAGE_KEY, locale);
  }
}

export function t(locale: Locale): DeepRecord<typeof translations.en> {
  return (translations[locale] || translations.en) as DeepRecord<typeof translations.en>;
}

export function useTranslations(locale: Locale): DeepRecord<typeof translations.en> {
  return (translations[locale] || translations.en) as DeepRecord<typeof translations.en>;
}

export { translations };
